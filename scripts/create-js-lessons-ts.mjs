/**
 * Creates src/lib/skills/content/js-lessons-data.ts
 * A TypeScript module that exports JS lessons as a typed array,
 * bypassing any Turbopack JSON import resolution issues.
 */
import { readFileSync, writeFileSync } from "fs";

const data = JSON.parse(
  readFileSync("src/lib/skills/content/js-lessons.json", "utf-8")
);

const lessons = data.lessons;

const tsContent = `// Auto-generated by scripts/create-js-lessons-ts.mjs — do not edit manually.
import type { Lesson } from "../catalog";

export const jsLessons: Lesson[] = ${JSON.stringify(lessons, null, 2)} as Lesson[];
`;

writeFileSync("src/lib/skills/content/js-lessons-data.ts", tsContent);
console.log(`✅ Created js-lessons-data.ts with ${lessons.length} lessons`);
